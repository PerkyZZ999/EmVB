/**
 * W-1024: the Social icons element's brand presets, taken from the Font Awesome Free set the
 * icon library ships (`packages/emvb-icons/fontawesome.json`, CC BY 4.0, see
 * packages/emvb/THIRD_PARTY_NOTICES.md). Public pages need the SVG without the library, so the
 * few presets are generated into core and committed; `build-social-icons.test.ts` fails when
 * they are out of date.
 *
 *   bun scripts/build-social-icons.ts
 */
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const SOURCE = join(ROOT, "packages/emvb-icons/fontawesome.json");
export const GENERATED = join(ROOT, "packages/emvb/src/core/icons/social.generated.ts");

/** Preset id → [Font Awesome name, style index (0 solid, 2 brands)], in the editor's order. */
export const PRESETS: Record<string, [string, number]> = {
  facebook: ["facebook", 2],
  instagram: ["instagram", 2],
  x: ["x-twitter", 2],
  linkedin: ["linkedin", 2],
  youtube: ["youtube", 2],
  tiktok: ["tiktok", 2],
  bluesky: ["bluesky", 2],
  mastodon: ["mastodon", 2],
  threads: ["threads", 2],
  github: ["github", 2],
  pinterest: ["pinterest", 2],
  whatsapp: ["whatsapp", 2],
  discord: ["discord", 2],
  twitch: ["twitch", 2],
  reddit: ["reddit", 2],
  dribbble: ["dribbble", 2],
  behance: ["behance", 2],
  telegram: ["telegram", 2],
  spotify: ["spotify", 2],
  email: ["envelope", 0],
  rss: ["rss", 0],
  website: ["globe", 0],
};

type IconSet = {
  styles: { viewBox: string }[];
  icons: [string, number, string, string, string, string?][];
};

/** The generated module's source. */
export async function generatedSource(): Promise<string> {
  const set = (await Bun.file(SOURCE).json()) as IconSet;
  const lines = [
    "// Generated by scripts/build-social-icons.ts (W-1024). Do not edit; run the script.",
    "// Font Awesome Free by Fonticons, Inc., CC BY 4.0 (THIRD_PARTY_NOTICES.md). Brand icons are",
    "// trademarks of their owners.",
    "",
    "/** Each Social icons preset's SVG: its viewBox and the shapes inside. */",
    "export const SOCIAL_ICONS = {",
  ];
  for (const [id, [name, style]] of Object.entries(PRESETS)) {
    const icon = set.icons.find((entry) => entry[0] === name && entry[1] === style);
    if (!icon) throw new Error(`Font Awesome has no ${name} in style ${style}`);
    const viewBox = icon[5] ?? set.styles[style]?.viewBox ?? "0 0 512 512";
    lines.push(
      `  ${id}: { viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(icon[3])} },`,
    );
  }
  lines.push("} as const;", "");
  return lines.join("\n");
}

if (import.meta.main) {
  await Bun.write(GENERATED, await generatedSource());
  // oxlint-disable-next-line no-console -- a CLI script reports what it wrote
  console.log(`Wrote ${GENERATED}`);
}
